function getItemDesc(card) {
    if (card.trophyWhite) {
        const def = window.AdventureRegistry && card.trophyName
            ? window.AdventureRegistry.getItem(card.trophyName) : null;
        return def && def.description ? def.description : "战利白卡：打出后抽1🃏，可搭桥";
    }
    if (card.isBlack) {
        if (card.shuffleToDeck) return "指定颜色，弃牌库除顶牌外洗入牌库，可搭桥";
        if (card.drawTwo) return "指定颜色，抽2🃏，可搭桥";
        return "指定颜色，可搭桥";
    }
    if (card.potion) return "回5❤️，可搭桥";
    if (card.drawThree) return "抽3🃏，可搭桥";
    if (card.swapHand) return "交换双方所有手牌，可搭桥";
    if (card.superPurify) return "选择一名角色，清除其所有buff与debuff（包括[守护]和[混沌]），可搭桥";
    if (card.purify) return "净化1层buff（[灼伤]/[冷冻]/[流血]/[中毒]/[守护]/[飞翔]/[暴击]等，自选），可搭桥";
    return "";
}

function getSkillDesc(charName, card, isDefend) {
    const name = charName.replace(/^AI\d*\s+/, "");
    if (card.isItemCard) return getItemDesc(card);
    const v = card.value;
    let desc;
    if (isDefend) {
        const descs = SKILL_DATA.defend[name];
        if (!descs) return "";
        // Classic layout is [1,2,3,0]. Longer layouts include high-card defend
        // lines before the trailing 0 (e.g. ForestRafflesia [1..6,0]).
        if (descs.length >= 7) {
            if (v === 0) desc = descs[descs.length - 1];
            else if (v === 7) desc = "无防御效果";
            else if (v >= 1 && v < descs.length) desc = descs[v - 1];
            else return "";
        } else {
            if (v === 0) desc = descs[3];
            else if (v >= 1 && v <= 3) desc = descs[v - 1];
            else if (v >= 4 && v <= 7) desc = "无防御效果";
            else return "";
        }
    } else {
        const descs = SKILL_DATA.attack[name];
        if (!descs) return "";
        if (v >= 0 && v <= 7) desc = descs[v === 0 ? 7 : v - 1];
        else return "";
    }
    return desc.replace(/^\d+\s*/, '');
}

window.SKILL_DATA = SKILL_DATA;
window.getSkillDesc = getSkillDesc;
window.getItemDesc = getItemDesc;
