function getItemDesc(card) {
    if (card.trophyWhite) {
        const def = window.AdventureRegistry && card.trophyName
            ? window.AdventureRegistry.getItem(card.trophyName) : null;
        return def && def.description ? def.description : "战利白卡：打出后抽1张牌，可搭桥继续出牌";
    }
    if (card.isBlack) {
        if (card.shuffleToDeck) return "指定颜色，弃牌库除顶牌外洗入牌库，可搭桥继续出牌";
        if (card.drawTwo) return "指定颜色，抽2张牌，可搭桥继续出牌";
        return "指定颜色，可搭桥继续出牌";
    }
    if (card.potion) return "恢复5[生命]，可搭桥继续出牌";
    if (card.drawThree) return "抽3张牌，可搭桥继续出牌";
    if (card.swapHand) return "交换双方所有手牌，可搭桥继续出牌";
    if (card.superPurify) return "选择一名角色，清除其所有buff与debuff（包括[守护]和[混沌]），可搭桥继续出牌";
    if (card.purify) return "净化1层buff（[灼伤]/[冷冻]/[流血]/[中毒]/[守护]/[飞翔]/[暴击]等，自选），可搭桥继续出牌";
    return "";
}

function skillRowIndex(v, descs) {
    if (!descs || !descs.length) return -1;
    if (v === 0) {
        if (descs.length >= 6) return 5;
        if (descs.length === 4) return 3;
        return descs.length - 1;
    }
    if (v === 5) return descs.length >= 5 ? 4 : -1;
    if (v >= 6 && v <= 7) return -1;
    if (v >= 1 && v <= 4) {
        if (descs.length >= 6) return v - 1;
        if (descs.length === 4 && v <= 3) return v - 1;
        if (descs.length >= 8) return v - 1;
        if (v - 1 < descs.length) return v - 1;
    }
    return -1;
}

function getSkillDesc(charName, card, isDefend) {
    const name = charName.replace(/^AI\d*\s+/, "");
    if (card.isItemCard) return getItemDesc(card);
    const v = card.value;
    const descs = isDefend ? SKILL_DATA.defend[name] : SKILL_DATA.attack[name];
    if (!descs) return "";
    if (isDefend && descs.length === 3 && v === 3) return "无防御效果";
    const idx = skillRowIndex(v, descs);
    if (idx < 0) return isDefend ? "无防御效果" : "";
    const desc = descs[idx];
    if (!desc) return isDefend ? "无防御效果" : "";
    return desc.replace(/^\d+\s*/, '');
}

window.SKILL_DATA = SKILL_DATA;
window.getSkillDesc = getSkillDesc;
window.getItemDesc = getItemDesc;
