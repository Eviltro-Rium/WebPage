function getItemDesc(card) {
    if (card.isBlack) {
        if (card.shuffleToDeck) return "指定颜色，弃牌库除顶牌外洗入牌库，可搭桥继续出牌";
        if (card.drawTwo) return "指定颜色，抽2张牌，可搭桥继续出牌";
        return "指定颜色，可搭桥继续出牌";
    }
    if (card.potion) return "恢复5[生命]，可搭桥继续出牌";
    if (card.drawThree) return "抽3张牌，可搭桥继续出牌";
    if (card.swapHand) return "交换双方所有手牌，可搭桥继续出牌";
    if (card.superPurify) return "选择一名角色，清除其所有buff与debuff（包括[守护]和[混沌]），可搭桥继续出牌";
    if (card.purify) return "净化1层debuff（[灼烧]/[冷冻]/[流血]），可搭桥继续出牌";
    return "";
}

function getSkillDesc(charName, card, isDefend) {
    const name = charName.replace("AI ", "");
    if (card.isItemCard) return getItemDesc(card);
    const v = card.value;
    let desc;
    if (isDefend) {
        const descs = SKILL_DATA.defend[name];
        if (!descs) return "";
        if (v === 0) desc = descs[3];
        else if (v >= 1 && v <= 3) desc = descs[v - 1];
        else if (v >= 4 && v <= 7) desc = "无防御效果";
        else return "";
    } else {
        const descs = SKILL_DATA.attack[name];
        if (!descs) return "";
        if (v >= 0 && v <= 7) desc = descs[v === 0 ? 7 : v - 1];
        else return "";
    }
    return desc.replace(/^\d+\s*/, '');
}
